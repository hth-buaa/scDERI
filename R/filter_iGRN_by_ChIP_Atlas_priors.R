#' @title Refine Initial GRNs with ChIP-Atlas Priors and Dual-Threshold QC
#'
#' @description This function refines cell-type-specific initial gene regulatory networks (iGRNs) using preprocessed ChIP-Atlas ChIP-seq prior data.
#' It performs prior-weighted edge correction, dual-threshold quality control with target gene rescue, and zero-preserving value transformation,
#' balancing network sparsity and numerical stability for downstream dynamic modeling.
#'
#' @param interest_cell_type_iGRN Named list. Output from \code{\link{get_iGRN_by_TFBS_pwm_by_JASPAR2024}},
#'   with each element being a target gene × TF association matrix.
#' @param min_scale Numeric in \[0, 1\]. Scaling factor for the lower bound in min-max normalization,
#'   applied in both pre-correction and post-correction steps. Defaults to \code{1}.
#' @param theta_i_top_quantile Numeric between 0 and 1. Global quantile threshold:
#'   edges with corrected scores in the top \code{theta_i_top_quantile} proportion are retained.
#'   Defaults to \code{0.15} (keep top 15%).
#' @param theta_i_top_n Positive integer. Per-TF top-N threshold:
#'   the top N targets of each TF are always retained regardless of global scores. Defaults to \code{50}.
#' @param theta_i_absolute_min Non-negative numeric. Absolute score floor.
#'   Corrected values below this threshold are set to zero before re-normalization. Defaults to \code{0.05}.
#' @param TG_rescue_number Non-negative integer. Minimum number of TF regulators guaranteed per target gene after QC filtering.
#'   If a TG has fewer non-zero edges than this value after dual-threshold QC, its top-\code{TG_rescue_number} pre-QC edges are restored.
#'   Set to \code{0} to disable rescue. Defaults to \code{1}.
#' @param TG_rescue_number Non-negative integer. Minimum number of regulators guaranteed per target gene after QC.
#'   TGs with fewer non-zero edges will have their top pre-QC edges restored. Set to \code{0} to disable rescue. Defaults to \code{1}.
#'
#' @return
#' A named list of the same structure as the input, containing refined iGRN matrices for each cell type.
#' Each matrix has been prior-weighted, quality-controlled and value-transformed:
#' \itemize{
#'   \item Non-zero edges fall in the range (0.1, 1.0\]
#'   \item Zero edges remain exactly zero to preserve sparse network structure
#'   \item All-zero rows (target genes) and columns (TFs) are automatically removed
#' }
#'
#' @details
#' The refinement pipeline is applied independently to each cell type and consists of three core stages:
#'
#' \enumerate{
#'   \item \strong{Prior-weighted edge correction}
#'     \itemize{
#'       \item Reads preprocessed ChIP-Atlas prior data from the standard output path of \code{\link{get_TFs_from_priors}}.
#'       \item For each TF, normalizes original PWM scores to \[0, 1\] via min-max scaling with \code{min_scale}-adjusted lower bound.
#'       \item Multiplies normalized scores by ChIP-seq prior intensity; TFs without prior support are zeroed out.
#'       \item Applies square-root transform to the product, and floors values below \code{theta_i_absolute_min} to zero.
#'       \item Re-normalizes corrected scores with the same \code{min_scale} offset and a 1.1× maximum expansion factor to cap values below 1.
#'     }
#'
#'   \item \strong{Dual-threshold QC with target gene rescue}
#'     \itemize{
#'       \item Computes a global intensity threshold as the \code{1 - theta_i_top_quantile} quantile of all positive corrected scores.
#'       \item For each TF, retains targets satisfying **either** the per-TF top-N rank **or** the global quantile threshold; all other edges are zeroed.
#'       \item If \code{TG_rescue_number > 0}, restores pre-QC top edges for any TG with fewer non-zero regulators than the threshold.
#'       \item Removes all-zero rows and columns from the final matrix.
#'     }
#'
#'   \item \strong{Zero-preserving minimum value correction}
#'     Applies linear transformation \code{x * 0.9 + 0.1} to all values, then resets values ≤ 0.1 back to exactly zero.
#'     This shifts non-zero edges into the (0.1, 1.0\] range for numerical stability in downstream gradient-based or log-transform operations,
#'     while fully retaining the sparse network structure.
#' }
#'
#' The prior file is read from the relative path
#' \code{../1.1 Data Preprocessing - Get TFs From Database/ChIP_Atlas_Priors/simplified_processed_priors.rds}
#' after switching into the \code{3 get iGRN/} working directory.
#'
#' @note
#' \itemize{
#'   \item This function depends on preprocessed ChIP-Atlas priors generated by \code{\link{get_TFs_from_priors}}.
#'     Ensure \code{simplified_processed_priors.rds} exists at the standard output path before running.
#'   \item The function creates (if missing) and temporarily switches to the \code{3 get iGRN/} directory during execution,
#'     and restores the original working directory on completion.
#'   \item Built-in input validation covers list structure, parameter ranges and prior file existence; invalid inputs trigger informative errors.
#'   \item TFs present in the input iGRN but absent from the prior table receive zero prior intensity and will be fully removed after QC.
#'   \item The dual-threshold mechanism ensures every TF retains a minimal set of targets while filtering out globally weak edges.
#'   \item The TG rescue mechanism prevents target genes from losing all regulatory connections during aggressive sparsification,
#'     maintaining basic network connectivity for downstream dynamic modeling.
#' }
#'
#' @export
#'
#' @examples
#' \dontrun{
#' # Load initial gene regulatory networks
#' interest_cell_type_iGRN <- readRDS("./3 get iGRN/interest_cell_type_iGRN.rds")
#'
#' # Refine iGRNs using preprocessed ChIP-Atlas priors with default parameters
#' interest_cell_type_iGRN <- filter_iGRN_by_ChIP_Atlas_priors(
#'   interest_cell_type_iGRN = interest_cell_type_iGRN,
#'   min_scale = 0.2,
#'   theta_i_top_quantile = 0.15,
#'   theta_i_top_n = 50,
#'   theta_i_absolute_min = 0.05,
#'   TG_rescue_number = 1
#' )
#'
#' saveRDS(interest_cell_type_iGRN, file = "./3 get iGRN/interest_cell_type_iGRN.rds")
#' }
#'
filter_iGRN_by_ChIP_Atlas_priors = function(
    interest_cell_type_iGRN,
    min_scale = 1,
    theta_i_top_quantile = 0.15,
    theta_i_top_n = 50,
    theta_i_absolute_min = 0.05,
    TG_rescue_number = 1
) {
  ### Input validation.
  # Validate primary input structure.
  if (!base::is.list(interest_cell_type_iGRN) || base::length(interest_cell_type_iGRN) == 0) {
    stop("Parameter 'interest_cell_type_iGRN' must be a non-empty named list of iGRN matrices.")
  }
  for (cell_type in base::names(interest_cell_type_iGRN)) {
    if (!base::is.matrix(interest_cell_type_iGRN[[cell_type]]) &&
        !base::is.data.frame(interest_cell_type_iGRN[[cell_type]])) {
      stop(base::sprintf("Element '%s' of 'interest_cell_type_iGRN' must be a matrix or data frame.", cell_type))
    }
  }

  # Validate QC threshold parameters.
  if (theta_i_top_quantile <= 0 || theta_i_top_quantile > 1) {
    stop("Parameter 'theta_i_top_quantile' must be in the range (0, 1].")
  }
  if (!base::is.numeric(theta_i_top_n) || theta_i_top_n < 1 || theta_i_top_n != base::round(theta_i_top_n)) {
    stop("Parameter 'theta_i_top_n' must be a positive integer.")
  }
  if (theta_i_absolute_min < 0) {
    stop("Parameter 'theta_i_absolute_min' must be non-negative.")
  }
  if (!base::is.numeric(TG_rescue_number) || TG_rescue_number < 0 || TG_rescue_number != base::round(TG_rescue_number)) {
    stop("Parameter 'TG_rescue_number' must be a non-negative integer.")
  }

  # Validate existence of preprocessed ChIP-Atlas prior file.
  priors_path = base::file.path(".", "1.1 Data Preprocessing - Get TFs From Database",
                                "ChIP_Atlas_Priors", "simplified_processed_priors.rds")
  if (!base::file.exists(priors_path)) {
    stop(base::sprintf("Preprocessed prior file not found: %s\nPlease run 'get_TFs_from_priors' first.", priors_path))
  }

  # Validate min_scalee.
  if (!base::is.numeric(min_scale) || min_scale <= 0) {
    stop("Parameter 'min_scale' must be a positive numeric value.")
  }
  if (min_scale > 1) {
    warning("Parameter 'min_scale' > 1.")
  }

  ### Start.
  t_start = base::Sys.time()
  message("Run: Filtering the global iGRN by ChIP-Atlas priors for each cell type. Time: ", t_start, ".")
  original_dir = base::getwd()
  new_folder = "3 get iGRN"
  if (!base::dir.exists(new_folder)) {
    base::dir.create(new_folder, recursive = TRUE)
    message("Folder created: ", new_folder, ".")
  } else {message("Folder already exists: ", new_folder, ".")}
  base::setwd(new_folder)
  message("The current working directory has been switched to: ", base::getwd(), ".")

  ### Read ChIP-Atlas priors.
  message("Read ChIP-Atlas priors.")
  priors_path = base::file.path("..", "1.1 Data Preprocessing - Get TFs From Database",
                                "ChIP_Atlas_Priors", "simplified_processed_priors.rds")
  priors_simplify = base::readRDS(priors_path)

  ### Fix iGRN for each cell type by prior intensity.
  message("Correcting iGRN weights with prior intensity for each cell type.")
  TG_rescue_number0 = TG_rescue_number
  for (cell_type in base::names(interest_cell_type_iGRN)) {
    message("[", cell_type, "] Correcting iGRN weights with prior intensity.")
    igrn = interest_cell_type_iGRN[[cell_type]]
    nTF = base::ncol(igrn)

    # Apply prior-based correction to each TF's regulatory weights.
    message("[", cell_type, "] Apply prior-based correction to each TF's regulatory weights.")
    for (tf in base::colnames(igrn)) {
      tf_tgs_igrn = igrn[, tf, drop = FALSE]

      # Rename column; min-max normalize theta with min_scale-adjusted lower bound, floor negatives to 0
      base::colnames(tf_tgs_igrn)[1] = "theta_i_before_fix"
      if (base::max(tf_tgs_igrn[, "theta_i_before_fix"]) == 0) {
        tf_tgs_igrn[, "norm_theta_i_before_fix"] <- 0
      } else {
        max_theta_i_before_fix = base::max(tf_tgs_igrn[, "theta_i_before_fix"]) + 0.0001
        min_theta_i_before_fix = base::min(tf_tgs_igrn[
          tf_tgs_igrn[, "theta_i_before_fix"] > 0,
          "theta_i_before_fix"
        ]) * min_scale
        tf_tgs_igrn[, "norm_theta_i_before_fix"] =
          (tf_tgs_igrn[, "theta_i_before_fix"] - min_theta_i_before_fix) /
          (max_theta_i_before_fix - min_theta_i_before_fix)
        tf_tgs_igrn[
          tf_tgs_igrn[, "norm_theta_i_before_fix"] < 0,
          "norm_theta_i_before_fix"
        ] = 0
      }

      # Incorporate prior intensity: use prior if available, otherwise set to 0
      if (!base::is.null(priors_simplify[[tf]])) {
        tf_tgs_igrn[, "prior_intensity"] = priors_simplify[[tf]][base::rownames(tf_tgs_igrn), "intensity"]
        tf_tgs_igrn[, "prior_intensity"][base::is.na(tf_tgs_igrn[, "prior_intensity"])] = 0
      } else {
        tf_tgs_igrn[, "prior_intensity"] = 0
      }

      # Compute corrected theta: weight by prior intensity, apply sqrt transform, floor values below absolute threshold to 0
      tf_tgs_igrn[, "theta_i_after_fix"] = base::with(tf_tgs_igrn, norm_theta_i_before_fix * prior_intensity)
      tf_tgs_igrn[, "theta_i_after_fix"] = tf_tgs_igrn[, "theta_i_after_fix"] ** 0.5
      tf_tgs_igrn[
        tf_tgs_igrn[, "theta_i_after_fix"] < theta_i_absolute_min,
        "theta_i_after_fix"
      ] = 0

      # Re-normalize corrected theta with consistent min_scale offset; max expanded by 1.1 to cap values below 1
      if (base::max(tf_tgs_igrn[, "theta_i_after_fix"]) > 0) {
        max_theta_i_after_fix = base::max(tf_tgs_igrn[, "theta_i_after_fix"]) + 0.0001
        min_theta_i_after_fix = base::min(tf_tgs_igrn[
          tf_tgs_igrn[, "theta_i_after_fix"] > 0,
          "theta_i_after_fix"]) * min_scale
        tf_tgs_igrn[, "norm_theta_i_after_fix"] =
          (tf_tgs_igrn[, "theta_i_after_fix"] - min_theta_i_after_fix) /
          (max_theta_i_after_fix * 1.1 - min_theta_i_after_fix)
        tf_tgs_igrn[
          tf_tgs_igrn[, "norm_theta_i_after_fix"] < 0,
          "norm_theta_i_after_fix"
        ] = 0
      } else {
        tf_tgs_igrn[, "norm_theta_i_after_fix"] = 0
      }

      # Update iGRN with corrected and normalized theta values
      igrn[, tf] = tf_tgs_igrn[base::rownames(igrn), "norm_theta_i_after_fix"]
    }

    # QC step: retain TGs passing EITHER per-TF top-N rank OR global quantile intensity threshold
    message("[", cell_type, "] QC: Retain TGs passing either top-", theta_i_top_n, " rank or minimum intensity (top ", theta_i_top_quantile*100, "%); zero others.")

    # Extract all positive theta values for global threshold calculation
    message("[", cell_type, " - QC] Extract all positive theta values for global threshold calculation.")
    positive_theta_i = base::unlist(igrn)
    positive_theta_i = positive_theta_i[positive_theta_i > 0]

    # Define minimum intensity threshold as quantile of positive weights
    message("[", cell_type, " - QC] Define minimum intensity threshold as quantile of positive weights.")
    min_theta_i = stats::quantile(x = positive_theta_i, probs = 1 - theta_i_top_quantile)
    TGs = base::rownames(igrn)

    # Pre-compute per-TG top TG_rescue_number TF and max theta for rescue
    if (TG_rescue_number0 > 0) {
      TG_rescue_number = base::min(TG_rescue_number0, nTF)
      message("[", cell_type, " - QC] Pre-compute per-TG top ", TG_rescue_number," TFs and theta_i for rescue.")
      TG_rescue = base::as.data.frame(base::matrix(
        0, nrow = base::length(TGs), ncol = 2 * TG_rescue_number,
        dimnames = base::list(TGs, base::c(
          base::paste0("top_TF", 1:TG_rescue_number),
          base::paste0("top_theta_i", 1:TG_rescue_number)
        ))
      ))
      for (tg in TGs) {
        top_TFs = base::colnames(igrn)[base::order(-base::as.numeric(igrn[tg, ]))][1:TG_rescue_number]
        TG_rescue[tg, base::paste0("top_TF", 1:TG_rescue_number)] = top_TFs
        TG_rescue[tg, base::paste0("top_theta_i", 1:TG_rescue_number)] = igrn[tg, top_TFs]
      }
    }

    # Apply QC filter per TF
    message("[", cell_type, " - QC] Apply QC filter per TF.")
    for (tf in base::colnames(igrn)) {
      tf_tgs_igrn_fixed = igrn[, tf, drop = FALSE]

      # Subset to TGs with non-zero weights for current TF
      tf_tgs_igrn_fixed = tf_tgs_igrn_fixed[tf_tgs_igrn_fixed[, 1] > 0, , drop = FALSE]
      TGs_all = base::rownames(tf_tgs_igrn_fixed)

      # Retain TGs in top-N rank
      tf_tgs_igrn_fixed$rank = base::rank(-tf_tgs_igrn_fixed[, 1], ties.method = "min")
      TGs_remaining_by_top = TGs_all[tf_tgs_igrn_fixed$rank <= theta_i_top_n]

      # Retain TGs above global intensity threshold
      TGs_remaining_by_min = TGs_all[tf_tgs_igrn_fixed[, 1] >= min_theta_i]

      # Zero weights for TGs failing both criteria
      TGs_remaining = base::union(TGs_remaining_by_top, TGs_remaining_by_min)
      igrn[base::setdiff(TGs, TGs_remaining), tf] = 0
    }

    # Rescue: restore top-N original TF edges for any TG with fewer than TG_rescue_number non-zero edges after QC
    if (TG_rescue_number > 0) {
      message("[", cell_type, " - QC] Rescue: restoring top TF edges for TGs below minimum non-zero count")
      for (tg in TGs) {
        positive_theta_i_number = base::sum(base::as.numeric(igrn[tg, ]) > 0)
        if (positive_theta_i_number < TG_rescue_number) {
          for (rn in 1:TG_rescue_number) {
            igrn[tg, TG_rescue[tg, base::paste0("top_TF", rn)]] =
              TG_rescue[tg, base::paste0("top_theta_i", rn)]
          }
        }
      }
    }

    # Remove all-zero rows (target genes) and columns (TFs)
    message("[", cell_type, "] Remove all-zero rows (target genes) and columns (TFs).")
    igrn = igrn[
      base::rowSums(igrn != 0) > 0,
      base::colSums(igrn != 0) > 0,
      drop = FALSE
    ]

    # Minimum value correction: shift non-zero values into (0.1, 1] range while preserving exact zeros
    message("[", cell_type, "] Applying minimum value correction (non-zero values to 0.1-1.0, exact zeros preserved).")
    igrn = igrn * 0.9 + 0.1
    igrn[igrn <= 0.1] = 0

    interest_cell_type_iGRN[[cell_type]] = igrn
  }

  ### End.
  base::setwd(original_dir)
  message("The current working directory has been switched to: ", base::getwd(), ".")
  t_end = base::Sys.time()
  message("Finish: Filtering the global iGRN by ChIP-Atlas priors for each cell type. Time: ", t_end, ".")
  message("Running time: ", base::format(t_end - t_start))
  return(interest_cell_type_iGRN)
}
